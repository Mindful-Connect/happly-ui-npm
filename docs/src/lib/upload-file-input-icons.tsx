/**
 * Returns the appropriate large thumbnail icon (48x48) based on mime type
 */
export const getFileThumbnailIcon = (
  mimeType: string,
  fileName?: string
): JSX.Element => {
  const type = mimeType?.toLowerCase() || '';
  const name = fileName?.toLowerCase() || '';

  if (type === 'application/pdf' || name.endsWith('.pdf')) {
    return pdfThumbnailIcon;
  }
  if (
    type === 'application/msword' ||
    type ===
      'application/vnd.openxmlformats-officedocument.wordprocessingml.document' ||
    name.endsWith('.doc') ||
    name.endsWith('.docx')
  ) {
    return wordThumbnailIcon;
  }
  if (type === 'text/csv' || name.endsWith('.csv')) {
    return csvThumbnailIcon;
  }
  if (
    type === 'application/vnd.ms-excel' ||
    type ===
      'application/vnd.openxmlformats-officedocument.spreadsheetml.sheet' ||
    name.endsWith('.xls') ||
    name.endsWith('.xlsx')
  ) {
    return excelThumbnailIcon;
  }
  if (
    type === 'application/vnd.ms-powerpoint' ||
    type ===
      'application/vnd.openxmlformats-officedocument.presentationml.presentation' ||
    name.endsWith('.ppt') ||
    name.endsWith('.pptx')
  ) {
    return pptThumbnailIcon;
  }
  if (
    type === 'application/zip' ||
    type === 'application/x-zip-compressed' ||
    type === 'application/x-rar-compressed' ||
    type === 'application/x-7z-compressed' ||
    name.endsWith('.zip') ||
    name.endsWith('.rar') ||
    name.endsWith('.7z')
  ) {
    return zipThumbnailIcon;
  }
  if (
    type.startsWith('image/') ||
    /\.(jpg|jpeg|png|gif|webp|svg|bmp|ico)$/i.test(name)
  ) {
    return imageThumbnailIcon;
  }
  if (type.startsWith('text/') || name.endsWith('.txt')) {
    return textThumbnailIcon;
  }
  if (fileTypes.video.includes(type)) {
    return genericVideoThumbnailIcon;
  }
  return genericThumbnailIcon;
};

