// SVG-drawn dashed border so dash length/gap match the design spec instead of
// browser defaults (which render dashes far too tight). stroke-width=2 because
// half is clipped by the element edge, leaving a crisp 1px visible stroke.
const dashedBorderImage = (hex: string) =>
  `url("data:image/svg+xml,%3Csvg%20xmlns='http://www.w3.org/2000/svg'%20width='100%25'%20height='100%25'%20fill='none'%3E%3Crect%20width='100%25'%20height='100%25'%20rx='12'%20ry='12'%20stroke='%23${hex}'%20stroke-width='2'%20stroke-dasharray='6%204'/%3E%3C/svg%3E")`;

const DASHED_BORDER_DEFAULT = dashedBorderImage('CACFD8');
const DASHED_BORDER_ACTIVE = dashedBorderImage('7D52F4');

const FileUploadRoot = React.forwardRef<
  HTMLLabelElement,
  React.LabelHTMLAttributes<HTMLLabelElement> & {
    asChild?: boolean;
    dragging?: boolean;
    disabled?: boolean;
  }
>(
  (
    {
      className,
      asChild,
      dragging,
      disabled,
      onDragOver,
      onDragLeave,
      onDrop,
      style,
      ...rest
    },
    forwardedRef
  ) => {
    const Component = asChild ? Slot : 'label';
    const [internalDragging, setInternalDragging] = React.useState(false);
    const dragCounter = React.useRef(0);

    const isDragging = dragging ?? internalDragging;

    const handleDragOver = React.useCallback(
      (e: React.DragEvent<HTMLLabelElement>) => {
        e.preventDefault();
        onDragOver?.(e);
      },
      [onDragOver]
    );

    const handleDragEnter = React.useCallback(
      (e: React.DragEvent<HTMLLabelElement>) => {
        e.preventDefault();
        dragCounter.current++;
        if (dragCounter.current === 1) {
          setInternalDragging(true);
        }
      },
      []
    );

    const handleDragLeave = React.useCallback(
      (e: React.DragEvent<HTMLLabelElement>) => {
        e.preventDefault();
        dragCounter.current--;
        if (dragCounter.current === 0) {
          setInternalDragging(false);
        }
        onDragLeave?.(e);
      },
      [onDragLeave]
    );

    const handleDrop = React.useCallback(
      (e: React.DragEvent<HTMLLabelElement>) => {
        e.preventDefault();
        dragCounter.current = 0;
        setInternalDragging(false);
        onDrop?.(e);
      },
      [onDrop]
    );

    return (
      <Component
        ref={forwardedRef}
        {...rest}
        className={cn(
          'bg-bg-white-0 flex w-full flex-col items-center gap-5 rounded-xl p-8 text-center',
          'transition duration-200 ease-out',
          disabled
            ? 'pointer-events-none opacity-60'
            : 'hover:bg-bg-weak-50 cursor-pointer',
          isDragging && !disabled && 'bg-primary-alpha-10',
          className
        )}
        style={{
          backgroundImage: isDragging
            ? DASHED_BORDER_ACTIVE
            : DASHED_BORDER_DEFAULT,
          ...style,
        }}
        onDragOver={handleDragOver}
        onDragEnter={handleDragEnter}
        onDragLeave={handleDragLeave}
        onDrop={handleDrop}
      />
    );
  }
);
FileUploadRoot.displayName = 'FileUploadRoot';

